// The lifecycle contract the plane calls, and the two first-slice backends.
//
// A backend owns *where* an instance runs; the plane owns the record, the owner check and
// the credentials. This slice never starts a real container: MemoryBackend is the test
// stand-in and ComposeBackend only materializes a compose project on disk. `upgrade` and
// `recycle` are part of the contract and fail loudly until a later slice implements them.
import { chmodSync, mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { createHash } from 'node:crypto'

export class NotImplementedError extends Error {
  constructor(operation) {
    super(`${operation} is not implemented in the management-plane skeleton`)
    this.name = 'NotImplementedError'
    this.code = 'NOT_IMPLEMENTED'
    this.operation = operation
  }
}

// `create/start/stop` resolve to `{ state, health }` where state is 'running' or 'stopped'.
export class LifecycleBackend {
  async create() {
    throw new NotImplementedError('create')
  }

  async start() {
    throw new NotImplementedError('start')
  }

  async stop() {
    throw new NotImplementedError('stop')
  }

  async upgrade() {
    throw new NotImplementedError('upgrade')
  }

  async recycle() {
    throw new NotImplementedError('recycle')
  }
}

// No process at all: the state machine the HTTP tests exercise.
export class MemoryBackend extends LifecycleBackend {
  constructor() {
    super()
    this.calls = []
  }

  async create() {
    this.calls.push('create')
    return { state: 'stopped', health: 'unknown' }
  }

  async start() {
    this.calls.push('start')
    return { state: 'running', health: 'ok' }
  }

  async stop() {
    this.calls.push('stop')
    return { state: 'stopped', health: 'unknown' }
  }
}

const DEFAULT_PORT_START = 31000
const DEFAULT_PORT_SPAN = 900

// Deterministic so materializing twice yields the same project. The next slice replaces
// this with real port allocation when a runner exists.
export function hostPortFor(id, { portStart = DEFAULT_PORT_START, portSpan = DEFAULT_PORT_SPAN } = {}) {
  const hash = createHash('sha256').update(String(id)).digest()
  return portStart + (hash.readUInt32BE(0) % portSpan)
}

// Writes `instances/<id>/compose.yaml` and `instances/<id>/control.env` (0600). It does not
// run `docker compose up`: `runner` is the injection point a later slice will use, and this
// slice must never call it.
export class ComposeBackend extends LifecycleBackend {
  constructor({ instancesDir, portStart = DEFAULT_PORT_START, portSpan = DEFAULT_PORT_SPAN, runner = null } = {}) {
    super()
    if (typeof instancesDir !== 'string' || instancesDir === '') {
      throw new TypeError('ComposeBackend needs an instancesDir')
    }
    this.instancesDir = instancesDir
    this.portStart = portStart
    this.portSpan = portSpan
    this.runner = runner
    this.calls = []
  }

  async create(instance, { controlToken } = {}) {
    this.calls.push('create')
    const materialized = this.materialize(instance, { controlToken })
    return { state: 'stopped', health: 'unknown', hostPort: materialized.hostPort, composePath: materialized.composePath }
  }

  // Recorded transitions only; no container is started in this slice.
  async start() {
    this.calls.push('start')
    return { state: 'running', health: 'unknown' }
  }

  async stop() {
    this.calls.push('stop')
    return { state: 'stopped', health: 'unknown' }
  }

  materialize(instance, { controlToken } = {}) {
    if (!instance || typeof instance.id !== 'string' || instance.id === '') {
      throw new TypeError('materialize needs an instance with an id')
    }
    if (typeof controlToken !== 'string' || !/^ctl_[0-9a-f]{32}$/.test(controlToken)) {
      throw new TypeError('materialize needs the instance control token')
    }
    const hostPort = hostPortFor(instance.id, { portStart: this.portStart, portSpan: this.portSpan })
    const dir = join(this.instancesDir, instance.id)
    mkdirSync(dir, { recursive: true, mode: 0o700 })
    chmodSync(dir, 0o700)

    const controlPath = join(dir, 'control.env')
    writeFileSync(
      controlPath,
      `FLYBOT_CONTROL_TOKEN=${controlToken}\nFLYBOT_INSTANCE_ID=${instance.id}\n`,
      { mode: 0o600 },
    )
    chmodSync(controlPath, 0o600)

    const composePath = join(dir, 'compose.yaml')
    const compose = [
      '# Generated by @flybot/plane — re-run materialize instead of editing this file.',
      `name: flybot-${instance.id}`,
      'services:',
      '  flybot:',
      '    image: flybot:local',
      `    container_name: flybot-${instance.id}`,
      '    network_mode: host',
      '    environment:',
      `      FLYBOT_PORT: "${hostPort}"`,
      `      FLYBOT_INSTANCE_ID: "${instance.id}"`,
      `      FLYBOT_CONTROL_URL: "http://127.0.0.1:${hostPort}"`,
      '    env_file:',
      '      - control.env',
      '    volumes:',
      '      - ./data:/data',
      '    restart: unless-stopped',
      '',
    ].join('\n')
    writeFileSync(composePath, compose, { mode: 0o644 })
    return { composePath, controlPath, hostPort }
  }
}
