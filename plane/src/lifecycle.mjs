// The lifecycle seam (#3113): the plane steers instances through this contract and never through
// a docker command of its own. Two backends ship in this slice — `MemoryBackend`, which moves
// state and nothing else, and `ComposeBackend`, which materializes a compose project per instance
// and deliberately does not run it. `upgrade` and `recycle` are on the contract so the second
// slice has a shape to fill; until then they refuse loudly instead of succeeding quietly.
import { chmodSync, mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { PRIVATE_DIR_MODE } from './store.mjs'

export class NotImplementedError extends Error {
  constructor(what) {
    super(`${what} is not implemented in this slice of #3113`)
    this.name = 'NotImplementedError'
    this.what = what
  }
}

// The contract every backend answers. `create` provisions, `start`/`stop` move the instance and
// report `{ state, health }`; `upgrade` and `recycle` exist as seams.
export class LifecycleBackend {
  /* eslint-disable-next-line no-unused-vars */
  create(instance) { throw new NotImplementedError(`${this.constructor.name}.create`) }
  /* eslint-disable-next-line no-unused-vars */
  start(instance) { throw new NotImplementedError(`${this.constructor.name}.start`) }
  /* eslint-disable-next-line no-unused-vars */
  stop(instance) { throw new NotImplementedError(`${this.constructor.name}.stop`) }
  /* eslint-disable-next-line no-unused-vars */
  upgrade(instance) { throw new NotImplementedError(`${this.constructor.name}.upgrade`) }
  /* eslint-disable-next-line no-unused-vars */
  recycle(instance) { throw new NotImplementedError(`${this.constructor.name}.recycle`) }
}

// For tests and for the plane's own bookkeeping: the same contract with no files and no
// processes. State is the plane's to persist — the backend only reports what it did.
export class MemoryBackend extends LifecycleBackend {
  create() { return { state: 'stopped', health: 'unknown' } }
  start() { return { state: 'running', health: 'ok' } }
  stop() { return { state: 'stopped', health: 'unknown' } }
}

// The first real backend. It writes `instances/<id>/compose.yaml` and `instances/<id>/control.env`
// (mode 0600) — a project a person or the next slice can `docker compose up` — and runs nothing:
// `runner` is the seam the docker-calling slice will use, and it stays at zero calls here. The
// compose file mirrors the repo's own `compose.yaml` (host networking, a loopback FLYBOT_PORT)
// rather than inventing a second topology.
export class ComposeBackend extends LifecycleBackend {
  constructor({ root, runner = null } = {}) {
    super()
    this.root = root
    this.runner = runner
  }

  materialize(instance, { controlToken }) {
    const dir = join(this.root, 'instances', instance.id)
    mkdirSync(dir, { recursive: true, mode: PRIVATE_DIR_MODE })
    const yaml = [
      `# Generated by @flybot/plane for instance ${instance.id} (#3113).`,
      `# Run it yourself: docker compose -p flybot-${instance.id} up -d --build`,
      `name: flybot-${instance.id}`,
      'services:',
      '  flybot:',
      '    build: ../../..',
      '    image: flybot:plane',
      '    restart: unless-stopped',
      '    network_mode: host',
      '    env_file:',
      '      - control.env',
      '    environment:',
      `      - FLYBOT_PORT=${instance.port}`,
      '    volumes:',
      `      - data:/data`,
      'volumes:',
      '  data:',
      '',
    ].join('\n')
    // The control credential rides in its own 0600 env file; the compose file itself stays
    // shareable (logs, code review) with no secret in it (#3113).
    const env = `FLYBOT_CONTROL_TOKEN=${controlToken}\n`
    writeFileSync(join(dir, 'compose.yaml'), yaml, { encoding: 'utf8', mode: 0o600 })
    writeFileSync(join(dir, 'control.env'), env, { encoding: 'utf8', mode: 0o600 })
    chmodSync(join(dir, 'control.env'), 0o600)
    return { dir, project: `flybot-${instance.id}`, port: instance.port }
  }

  create(instance, { controlToken } = {}) {
    if (controlToken) this.materialize(instance, { controlToken })
    return { state: 'stopped', health: 'unknown' }
  }

  start() { return { state: 'running', health: 'ok' } }
  stop() { return { state: 'stopped', health: 'unknown' } }
}
